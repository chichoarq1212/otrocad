'use strict';
const assert=require('node:assert/strict');
const planner=require('../editor/arqui-planner.js');
const knowledge=require('../editor/arqui-knowledge.js');
global.window={OtroCadArquiPlanner:planner,OtroCadArchitecturalKnowledge:knowledge};
require('../editor/arqui-house-layout.js');
const engine=global.window.OtroCadArquiPlanner;
const professional=require('../editor/arqui-professional.js');

const prompt='Quiero una casa 10 x 8 con 3 habitaciones - dos de ellas con baño compartido y una con baño master - sala comedor y cocina con isla puerta trasera para salir a patio de 3 metros de fondo con lavanderia. parque 2 carros';
const spec=engine.parsePrompt(prompt);
assert.equal(spec.dimensionMeaning,'house');
assert.deepEqual([spec.houseWidth,spec.houseDepth],[10,8]);
assert.deepEqual([spec.lotWidth,spec.lotDepth],[10,8]);
assert.equal(spec.siteDeclared,false);
assert.equal(spec.siteAssumed,false);
assert.equal(spec.floors,2);
assert.equal(spec.bathrooms,2);
assert.equal(spec.garageSpaces,2);
assert.equal(spec.patioDepth,3);
const plan=engine.design(spec);
assert.equal(plan.floors.length,2);
const bedrooms=plan.floors.flatMap(f=>f.rooms).filter(r=>r.kind==='bedroom');
const baths=plan.floors.flatMap(f=>f.rooms).filter(r=>r.kind==='bath');
assert.equal(bedrooms.length,3);
assert.equal(baths.length,2);
assert.equal(plan.garage.spaces,2);
assert.equal(plan.garage.layout,'side-by-side');
assert.equal(plan.patio.laundry,true);
assert.deepEqual(plan.audit,[]);
const entities=professional.generate(plan,{units:'m',origin:{x:0,y:0},projectId:'regression'});
assert(entities.length>300&&entities.length<3300);
assert(!entities.some(x=>x.layer==='AI-ARQ-TERRENO'),'No fictional parcel allowed');
const labels=entities.filter(x=>x.type==='text').map(x=>x.text);
assert(labels.includes('PARQUEO 1')&&labels.includes('PARQUEO 2'));
assert(labels.some(x=>x.includes('PATIO POSTERIOR')));
assert(labels.includes('LAVANDERÍA'));
assert(entities.some(e=>e.type==='arc'&&e.aiElement==='door-swing'&&e.pts?.some(p=>Math.abs(p.y-8)<.01)));
const adjust=engine.interpret('agranda la cocina 50 cm',spec);
assert.equal(adjust.spec.dimensionMeaning,'house');
const revised=engine.design(adjust.spec);
assert(revised.floors[0].rooms[0].depth<plan.floors[0].rooms[0].depth);
const other=engine.parsePrompt('Quiero una vivienda de 1 planta en terreno 12x20 con 3 dormitorios y garaje',spec);
assert.notEqual(other.dimensionMeaning,'house');
assert.deepEqual([other.lotWidth,other.lotDepth],[12,20]);
assert.equal(engine.design(other).floors.length,1);
console.log('OK El Arqui: casa 10x8, 3 dormitorios, 2 baños, 2 parqueos, patio, salida, cambios y lote independiente');

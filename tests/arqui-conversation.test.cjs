'use strict';
const assert=require('node:assert/strict');
const p=require('../editor/arqui-planner.js');
const refs=require('../editor/arqui-references.js');
const pro=require('../editor/arqui-professional.js');
const base=p.parsePrompt('Casa de doce por veinte, tres dormitorios, dos baños, garaje en Quito');
assert.deepEqual([base.lotWidth,base.lotDepth,base.bedrooms,base.bathrooms,base.location],[12,20,3,2,'quito']);
assert.equal(p.parsePrompt('Lote de 14 metros de frente por 25 metros de fondo',base).lotDepth,25);
const first=p.interpret('Amplía la cocina cincuenta cm',base);
const second=p.interpret('Amplía la cocina otros 50 cm',first.spec);
assert.equal(second.spec.kitchenExtra,1);
assert.equal(second.spec.bedrooms,3);
const kitchen=s=>p.design(s).floors[0].rooms.find(r=>r.name==='COCINA').depth;
assert.ok(Math.abs(kitchen(second.spec)-kitchen(base)-1)<.003,'Actual kitchen depth must increase by the cumulative requested metre');
assert.equal(p.parsePrompt('reduce la cocina 25 cm',second.spec).kitchenExtra,.75);
assert.equal(p.parsePrompt('quita el garaje',base).garage,false);
assert.equal(p.parsePrompt('un baño',base).bathrooms,1);
assert.ok(Math.abs(kitchen(p.parsePrompt('reduce la cocina 25 cm',base))-kitchen(base)+.25)<.003);
assert.equal(p.parsePrompt('quita un dormitorio',base).bedrooms,2);
assert.equal(p.parsePrompt('agrega otro dormitorio',base).bedrooms,4);
const without=p.design(p.parsePrompt('quita la lavandería y sin vestidor',base));
assert.ok(!without.floors.flatMap(f=>f.rooms).some(r=>/LAVANDER|VESTIDOR/.test(r.name)));
for(const floors of [1,2])for(const bathrooms of [1,2,3,4]){
 const plan=p.design({...base,lotDepth:40,floors,bathrooms});
 assert.equal(plan.floors.flatMap(f=>f.rooms).filter(r=>r.kind==='bath').length,bathrooms);
 assert.equal(plan.floors.flatMap(f=>f.rooms).filter(r=>r.kind==='bedroom').length,3);
}
const single=p.design({...base,floors:2,bedrooms:1});
assert.equal(single.floors.flatMap(f=>f.rooms).filter(r=>r.kind==='bedroom').length,1,'No phantom bedroom on upper floor');
assert.throws(()=>p.validateSpec({...base,floors:1.5}),/entero/);
assert.equal(p.interpret('Mueve la cocina al fondo',base).canGenerate,false);
assert.ok(p.interpret('Quiero un hospital',base).unsupported.length);
assert.equal(p.interpret('Hola amigo',base).canGenerate,false);
const plan=p.design(base),entities=pro.generate(plan,{units:'cm',origin:{x:123,y:456},projectId:'saved-plan'});
assert.deepEqual(entities[0].aiDesignSpec,plan.spec);
assert.deepEqual(entities[0].aiDesignOrigin,{x:123,y:456});
assert.equal(entities[0].aiDesignUnits,'cm');
assert.ok(plan.floors[0].rooms.every(r=>r.netArea<r.area&&r.netArea>0),'Net area must exclude wall thickness');
const audit=refs.review(plan);
assert.ok(audit.some(r=>r.message.includes('1.20 m')&&r.sourceId==='nec-au'));
assert.ok(audit.some(r=>r.status==='pendiente'));
assert.ok(refs.builtins().find(r=>r.source==='Neufert').status.includes('libro completo no incorporado'));
assert.match(refs.consult('¿Cumple Neufert y la normativa?',plan),/libro no consultadas|no se atribuye|no atribuye|páginas del libro/);
assert.equal(refs.consult('Quiero una casa con criterio accesible',plan),null);
console.log('Conversation checks passed: natural brief, cumulative geometric edits, exact bath count, removed rooms, saved model context, net areas and scoped sources.');

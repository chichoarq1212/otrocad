'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const planner=require('../editor/arqui-planner.js');
const professional=require('../editor/arqui-professional.js');
const prompt='Plano terreno 12 x 20, tres dormitorios, retiro frontal de 3m posterior de 2m laterales de 1m, garaje para dos autos, muros exteriores de 20cm e interiores de 15cm, mobiliario hatch acotado tipo concurso';
const spec=planner.parsePrompt(prompt);
assert.equal(spec.lotWidth,12);assert.equal(spec.lotDepth,20);
assert.equal(spec.frontSetback,3);assert.equal(spec.backSetback,2);assert.equal(spec.sideSetback,1);
assert.equal(spec.garageSpaces,2);assert.equal(spec.wallOuter,.2);assert.equal(spec.wallInner,.15);
assert.equal(spec.style,'concurso');assert.equal(spec.furniture,true);
assert.equal(spec.wallHatch,true);assert.equal(spec.dimensions,true);
const plan=planner.design(spec),shapes=professional.generate(plan,{origin:{x:743250,y:9981230},units:'m',projectId:'a1'});
assert.ok(plan.garage&&plan.garage.spaces===2,'One side tandem bay must have room for two cars');
assert.ok(plan.warnings.some(x=>/TÁNDEM/i.test(x)));
assert.ok(shapes.length>180,'Professional design must have many real CAD entities');
assert.ok(shapes.every(x=>x.aiArchitect&&x.aiProjectId==='a1'));
assert.ok(shapes.every(x=>['line','circle','polygon','arc','text'].includes(x.type)));
const selected=role=>shapes.filter(e=>e.aiElement===role);
assert.ok(selected('wall').length>=20);
assert.ok(selected('wall-hatch').length>=20);
assert.ok(selected('wall-hatch').every(e=>e.type==='polygon'&&e.hatchPattern==='ANSI31'));
assert.ok(selected('door').length>=3);
assert.ok(selected('door-swing').length>=3);
assert.ok(selected('window').length>=6);
assert.ok(selected('bed').length===3);
assert.ok(selected('sink').length>=2);
assert.ok(selected('wc').length>=1);
assert.ok(selected('car').length===2);
assert.ok(selected('dimension-label').length>=7);
assert.ok(selected('north').length>=3);
assert.ok(selected('floor-title').length===1);
assert.ok(selected('scale-bar').length===4);
assert.ok(shapes.some(e=>e.layer==='AI-ARQ-MUROS'));
assert.ok(shapes.some(e=>e.layer==='AI-ARQ-HATCH-MUROS'));
assert.ok(shapes.some(e=>e.layer==='AI-ARQ-MOBILIARIO'));
assert.ok(shapes.some(e=>e.layer==='AI-ARQ-LÁMINA'));
const geo=shapes.flatMap(x=>(x.pts||[]).concat(x.a?[x.a]:[],x.b?[x.b]:[]));
assert.ok(geo.every(p=>Number.isFinite(p.x)&&Number.isFinite(p.y)));
assert.ok(geo.some(p=>p.x>743250),'Geometry should follow large coordinate insertion');
const noFurniture=planner.design({...spec,garage:false,furniture:false,wallHatch:false,dimensions:false,style:'esquematico'});
const simple=professional.generate(noFurniture,{units:'mm',projectId:'a2'});
assert.equal(simple.filter(e=>e.aiElement==='wall-hatch').length,0);
assert.equal(simple.filter(e=>e.aiElement==='bed').length,0);
assert.equal(simple.filter(e=>e.aiElement==='dimension-label').length,0);
assert.ok(simple.filter(e=>e.aiElement==='wall').some(e=>e.pts?.some(p=>p.x>1500)));
const two=planner.design({...spec,garageSpaces:1,sideSetback:.45,floors:2});
const twoShapes=professional.generate(two);
assert.equal(twoShapes.filter(e=>e.aiElement==='floor-title').length,2);
assert.ok(twoShapes.some(e=>e.aiElement==='stair-tread'));
let rendered=0;const svg={children:[],setAttribute(){},replaceChildren(){this.children=[]},append(n){this.children.push(n)}};
const document={createElementNS:(ns,tag)=>({
 tagName:tag,attributes:{},children:[],setAttribute(k,v){this.attributes[k]=v},
 append(x){this.children.push(x)},textContent:''
})};
professional.preview(document,svg,shapes);rendered=svg.children.length;
assert.ok(rendered>50,'Preview should contain actual walls, furniture and CAD lines');
assert.ok(svg.children.some(x=>x.tagName==='polygon'));
assert.ok(svg.children.some(x=>x.tagName==='text'));
const html=fs.readFileSync('editor/index.html','utf8'),assistant=fs.readFileSync('editor/arqui-assistant.js','utf8');
assert.ok(html.includes('src="arqui-professional.js"'));
assert.match(assistant,/professional\.generate\(proposed/);
assert.match(assistant,/professional\.preview\(document/);
assert.match(assistant,/arquiSetFront/);
assert.match(assistant,/arquiWallOuter/);
assert.match(assistant,/arquiFurniture/);
assert.match(assistant,/arquiDimensions/);
assert.match(assistant,/Te propongo/,'Architect should explain the proposal');
console.log('Arqui professional checks passed: responsive brief, UTM/CAD entities, thick walls, hatches, furniture, cars, doors/windows, dimension chains and real preview.');

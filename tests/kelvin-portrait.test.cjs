'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const asset='editor/assets/ing-kelvin.webp';
const img=fs.readFileSync(asset);
assert.ok(img.length>2500,'El retrato de Keeelvin no debe estar vacío');
assert.equal(img.toString('ascii',0,4),'RIFF');
assert.equal(img.toString('ascii',8,12),'WEBP');
assert.equal(img.toString('ascii',12,16),'VP8X');
assert.ok((img[20]&0x10)!==0,'El avatar debe conservar transparencia alpha');
const script=fs.readFileSync('editor/kelvin-assistant.js','utf8');
const styles=fs.readFileSync('editor/jaimito-assistant.css','utf8');
const html=fs.readFileSync('editor/index.html','utf8');
const worker=fs.readFileSync('sw.js','utf8');
const build=fs.readFileSync('scripts/build-pages.cjs','utf8');
assert.match(script,/class="kelvin-portrait" src="assets\/ing-kelvin\.webp"/);
assert.doesNotMatch(script,/kelvin-illustration/,'Nunca utilizar el antiguo dibujo SVG');
assert.match(styles,/\.kelvin-mascot img\.kelvin-portrait/);
assert.match(styles,/object-fit:contain/);
assert.match(styles,/orientation:landscape/);
assert.match(script,/\[data-tab="mep"\]\.active,\[data-tab="hvac"\]\.active/,'El avatar solo aparece en MEP/HVAC');
assert.match(script,/root\.hidden=!isActive\(\)/);
assert.match(script,/mep\.chooseSystem/,'El chat conserva acceso a las herramientas MEP');
assert.match(html,/src="kelvin-assistant\.js"/);
assert.ok(worker.includes('./editor/assets/ing-kelvin.webp'),'El modo offline debe incluir el avatar');
assert.ok(build.includes("'editor/assets/ing-kelvin.webp'"),'El instalador debe incluir el avatar');
console.log('Ing. Keeelvin: retrato real y transparente, widget MEP/HVAC, offline y paquete web verificados.');

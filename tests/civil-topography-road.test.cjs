'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const points=require('../editor/civil-points.js');
const road=require('../editor/civil-road.js');
const pnez='1 9976534.22 742345.81 2540.12 BM-1\n2 9976540.15 742350.33 2540.60 EJE-1\n3 9976555.41 742362.02 2541.05 EJE-2';
const block=points.parse(pnez);
assert.equal(block.points.length,3);
assert.deepEqual(block.points[0],{id:'1',north:9976534.22,east:742345.81,z:2540.12,description:'BM-1'});
assert.equal(block.points[2].description,'EJE-2');
const csv=points.parse('NUMERO,NORTE,ESTE,COTA,DESCRIPCION\n1,9976534.22,742345.81,2540.12,BM-1\n2,9976540.15,742350.33,2540.60,EJE-1');
assert.equal(csv.points[0].east,742345.81);
assert.equal(csv.points[0].z,2540.12);
assert.equal(csv.points[1].id,'2');
const decimalComma=points.parse('1 9976534,22 742345,81 2540,12 BM-1\n2 9976540,15 742350,33 2540,60 EJE-1');
assert.equal(decimalComma.delimiter,'whitespace');
assert.equal(decimalComma.points[1].north,9976540.15);
assert.equal(decimalComma.points[1].z,2540.60);
const semi=points.parse('Norte;Este;Cota;Descripción\n9976534,22;742345,81;2540,12;BM-1');
assert.equal(semi.points.length,1);
assert.equal(semi.points[0].description,'BM-1');
const enzd=points.parse('742345.81 9976534.22 2540.12 BM-1',{order:'ENZD'});
assert.equal(enzd.points[0].east,742345.81);
assert.equal(enzd.points[0].north,9976534.22);
const nezd=points.parse('9976534.22 742345.81 2540.12 BM-1');
assert.equal(nezd.points[0].id,'1');
assert.equal(nezd.points[0].description,'BM-1');
const nez=points.parse('9976534.22 742345.81 2540.12');
assert.equal(nez.points[0].north,9976534.22);
const withInvalid=points.parse('P,N,E,Z,D\n1,9976534,742345,2540,BM\n2,INVALID,742350,2541,BAD');
assert.equal(withInvalid.invalidRows.length,1);
assert.throws(()=>points.parse('1 2'),/No se reconocieron puntos|columnas/);
assert.throws(()=>points.parse('1 9976534 742345 2540',{order:'NE'}),/formato/);
const untouched=JSON.stringify(block.points);
const model=points.entities(block.points,(e,n)=>({x:e*1000,y:n*1000}));
assert.equal(model[0].a.x,742345810);
assert.equal(model[0].a.y,9976534220);
assert.equal(model[0].civilDescription,'BM-1');
const poly=points.polyline(block.points);
assert.equal(poly.type,'poly');
assert.equal(poly.pts.length,3);
assert.equal(poly.civilVertexElevations[0],2540.12);
assert.equal(JSON.stringify(block.points),untouched,'Never mutate topographic source points');

const alignment=[{x:0,y:0},{x:20,y:0}];
const original=JSON.stringify(alignment);
const continuous=road.generate(alignment,'solid');
assert.equal(continuous.length,1);
assert.equal(continuous[0].type,'line');
assert.equal(continuous[0].b.x,20);
assert.ok(continuous[0].civilRoadMarking);
assert.equal(JSON.stringify(alignment),original,'Never mutate the selected alignment');
const dashed=road.generate(alignment,'dashed',{dash:3,gap:4});
assert.ok(dashed.length>=2&&dashed.length<=4);
assert.equal(dashed[0].b.x,3);
assert.equal(dashed[1].a.x,7);
const bend=road.generate([{x:0,y:0},{x:4,y:0},{x:4,y:9}],'dashed',{dash:6,gap:2});
assert.ok(bend.every(o=>o.type==='line'),'Dashes remain native CAD line segments');
const dual=road.generate(alignment,'double');
assert.equal(dual.length,2);
assert.notEqual(dual[0].a.y,dual[1].a.y);
const zebra=road.generate(alignment,'crosswalk',{width:4});
assert.ok(zebra.length>=3);
assert.ok(zebra.every(s=>s.type==='polygon'&&s.pts.length===4));
const arrow=road.generate(alignment,'arrow');
assert.equal(arrow.length,3);
const sign=road.generate(alignment,'sign',{label:'PARE'});
assert.ok(sign.some(s=>s.type==='circle')&&sign.some(s=>s.type==='text'&&s.text==='PARE'));
const mmRoad=road.generate([{x:0,y:0},{x:20000,y:0}],'solid',{units:'mm'});
assert.equal(mmRoad[0].b.x,20000);
assert.throws(()=>road.generate(alignment,'unknown'),/desconocido/);
assert.throws(()=>road.generate(alignment,'solid',{width:-1}),/ancho/);
assert.throws(()=>road.generate([{x:0,y:0},{x:0,y:0}],'solid'),/longitud/);
const html=fs.readFileSync('editor/index.html','utf8');
const cad=fs.readFileSync('editor/editor.js','utf8');
const civil=fs.readFileSync('editor/civil3d.js','utf8');
const geo=fs.readFileSync('editor/geolocation.js','utf8');
const topoUI=fs.readFileSync('editor/civil-topography.js','utf8');
const roadUI=fs.readFileSync('editor/civil-road.js','utf8');
const kelvin=fs.readFileSync('editor/kelvin-assistant.js','utf8');
const mep=fs.readFileSync('editor/mep.js','utf8');
assert.match(cad,/function civilUtmInputActive\(\)/);
assert.match(cad,/civil\?'E \(UTM m\)'/,'Civil cursor must use E instead of X');
assert.match(cad,/civil\?'N \(UTM m\)'/,'Civil cursor must use N instead of Y');
assert.match(cad,/coordinatePoint\(x,y\)[\s\S]*?if\(civilUtmInputActive\(\)\)/);
assert.match(topoUI,/Polilínea UTM N\/E\/Z/);
assert.match(topoUI,/Pegar TXT \/ BLOCK/);
assert.match(topoUI,/function showPolylineDialog\(\)/);
assert.match(geo,/utmToModel:\(pair,units\)/);
assert.match(civil,/OtroCadCivilPoints\.parse/);
assert.match(roadUI,/SEÑALIZACIÓN VIAL/);
assert.match(kelvin,/Ing\. Keeeeeeelvin/);
assert.match(kelvin,/mep\.chooseSystem/);
assert.match(kelvin,/window\.OTROCAD_KELVIN_AI_ENDPOINT/);
assert.match(mep,/getQuantities:\(\)=>quantities/);
const scripts=[...html.matchAll(/<script src="([^"]+)"/g)].map(m=>m[1]);
for(const asset of ['civil-points.js','civil-topography.js','civil-road.js','kelvin-assistant.js'])
 assert.ok(scripts.includes(asset),'Editor must load '+asset);
assert.ok(scripts.indexOf('civil-points.js')<scripts.indexOf('civil3d.js'));
assert.ok(scripts.indexOf('geolocation.js')<scripts.indexOf('civil-topography.js'));
assert.ok(scripts.indexOf('mep.js')<scripts.indexOf('kelvin-assistant.js'));
assert.match(html,/civil-topography\.css/);
for(const path of ['editor/civil-points.js','editor/civil-topography.js','editor/civil-road.js','editor/kelvin-assistant.js'])
 assert.ok(fs.existsSync(path));
console.log('Civil UTM/TXT, road marking and Kelvin integrations passed: PNEZD import, precise E/N, native CAD entities and responsive assistant.');

'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const core=require('../editor/arqui-planner.js');
const knowledge=require('../editor/arqui-knowledge.js');
const professional=require('../editor/arqui-professional.js');
const sandbox={window:{OtroCadArquiPlanner:core,OtroCadArchitecturalKnowledge:knowledge}};
vm.runInNewContext(fs.readFileSync('editor/arqui-house-layout.js','utf8'),sandbox);
const engine=sandbox.window.OtroCadArquiPlanner;
function simulate(prompt,base={}){
 const spec=engine.parsePrompt(prompt,base),plan=engine.design(spec),shapes=professional.generate(plan);
 return {spec,plan,shapes};
}
const only=simulate('Hazme una casa de 10 por 8 metros, tres dormitorios, sala comedor y cocina');
assert.equal(only.spec.dimensionMeaning,'house');
assert.equal(only.spec.siteDeclared,false);
assert.deepEqual([only.spec.houseWidth,only.spec.houseDepth],[10,8]);
assert.deepEqual([only.spec.frontSetback,only.spec.backSetback,only.spec.sideSetback],[0,0,0]);
assert.equal(only.spec.garage,false,'Do not invent parking');
assert.equal(only.spec.patioDepth,0,'Do not invent a patio');
assert.equal(only.plan.garage,null);
assert.equal(only.plan.patio,null);
assert.equal(only.shapes.filter(e=>e.layer==='AI-ARQ-TERRENO').length,0,
 'Do not draw any invented lot, cadastral boundary or setback');
assert(!only.shapes.some(e=>e.type==='text'&&/TERRENO|PARCELA HIPOTÉTICA|RETIRO FRONTAL/.test(e.text)));
assert(only.shapes.length>350);
assert.equal(knowledge.spatialReview(only.plan).issues.length,0);
const outdoor=simulate('Quiero casa 10x8 con 3 habitaciones, patio posterior de 3 metros con lavanderia y parqueo para dos carros');
assert.equal(outdoor.spec.dimensionMeaning,'house');
assert.equal(outdoor.spec.siteDeclared,false);
assert.equal(outdoor.spec.garage,true);
assert.equal(outdoor.spec.garageSpaces,2);
assert.equal(outdoor.plan.patio.depth,3);
assert.equal(outdoor.plan.patio.laundry,true);
assert(outdoor.plan.garage.y<0,'Parking is a separate exterior requested zone, not a fake setback');
assert.equal(outdoor.shapes.filter(e=>e.layer==='AI-ARQ-TERRENO').length,0);
for(const label of ['PARQUEO 1','PARQUEO 2','LAVANDERÍA'])
 assert(outdoor.shapes.some(e=>e.type==='text'&&e.text===label),'Missing outdoor element '+label);
const both=simulate('Diseña una casa 10 por 8 en terreno de 15 x 24 con retiros frontal 3, posterior 2, laterales 1 y jardín frontal 2 m');
assert.equal(both.spec.siteDeclared,true);
assert.equal(both.spec.dimensionMeaning,'house');
assert.deepEqual([both.spec.houseWidth,both.spec.houseDepth],[10,8]);
assert.deepEqual([both.spec.lotWidth,both.spec.lotDepth],[15,24]);
assert.deepEqual([both.spec.frontSetback,both.spec.backSetback,both.spec.sideSetback],[3,2,1]);
assert.equal(both.spec.gardenFrontDepth,2);
assert(both.shapes.some(e=>e.type==='text'&&e.text.includes('JARDÍN FRONTAL')));
assert(both.shapes.some(e=>e.type==='text'&&e.text.includes('TERRENO 15')&&e.text.includes('24')));
assert(both.shapes.some(e=>e.layer==='AI-ARQ-TERRENO'));
const site=simulate('Terreno de 15 por 24 metros, retiros frontal 3, posterior 2 y laterales 1. Jardín posterior 2 metros');
assert.equal(site.spec.siteDeclared,true);
assert.equal(site.spec.dimensionMeaning,'site');
assert.deepEqual([site.spec.lotWidth,site.spec.lotDepth],[15,24]);
assert.deepEqual([site.spec.frontSetback,site.spec.backSetback,site.spec.sideSetback],[3,2,1]);
assert.equal(site.spec.gardenBackDepth,2);
assert(site.shapes.some(e=>e.type==='text'&&e.text.includes('JARDÍN POSTERIOR')));
assert(site.shapes.some(e=>e.layer==='AI-ARQ-TERRENO'));
const bedrooms=engine.parsePrompt('Casa de 12 x 8 con tres dormitorios y dos baños, una planta');
assert.equal(bedrooms.floors,1);
assert.equal(bedrooms.bathrooms,2);
const gardenOnly=simulate('Casa de 10 x 8, jardín delantero de 2 m',only.spec);
assert.equal(gardenOnly.spec.siteDeclared,false);
assert.equal(gardenOnly.spec.garage,false);
assert(gardenOnly.plan.gardens.length===1);
assert(gardenOnly.shapes.some(e=>e.type==='text'&&e.text.includes('JARDÍN FRONTAL')));
assert.equal(gardenOnly.shapes.filter(e=>e.layer==='AI-ARQ-TERRENO').length,0);
const follow=engine.interpret('Agranda la cocina 50 cm',only.spec);
assert.equal(follow.canGenerate,true);
assert.equal(follow.spec.dimensionMeaning,'house');
assert.equal(follow.spec.siteDeclared,false);
assert(follow.spec.kitchenExtra>0);
const source=knowledge.sources.find(s=>s.id==='neufert-upload-parte1');
assert(source);
assert(knowledge.neufertMethod.length>=15);
for(const p of [188,225,230,232,235,241,247])
 assert(knowledge.neufertMethod.some(r=>r.pdfPages.includes(p)),
  'Missing original Neufert learning section '+p);
assert.equal(typeof knowledge.spatialReview,'function');
const assistant=fs.readFileSync('editor/arqui-assistant.js','utf8');
assert(!assistant.includes('PARCELA HIPOTÉTICA'));
assert(!assistant.includes('franja frontal de parqueo'));
assert(assistant.includes('NO se inventa ninguna parcela'));
assert(assistant.includes('CASA ancho'));
assert(assistant.includes("s.siteDeclared"));
console.log('PASS natural requests: house ≠ site, setbacks require explicit terms, garden and patio separate, room programs preserved, Neufert method loaded, 0 calls to generative AI.');

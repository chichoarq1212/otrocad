'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('editor/editor.js','utf8');
function extract(first,last){const a=source.indexOf(first),b=source.indexOf(last,a);assert.ok(a>=0&&b>a,'Missing '+first);return source.slice(a,b)}
const grips=extract('function gripDescriptors(s){','function applyGrip(s,key,q){');
const objects=[{type:'line',a:{x:0,y:0},b:{x:100,y:0},layer:'General'}];
const screen=p=>p;
const context={window:{matchMedia:()=>({matches:false})},objects,screen,selectedItems:()=>[0],isVisibleModelEntity:()=>true,lockedLayers:new Set(),distance:(a,b)=>Math.hypot(a.x-b.x,a.y-b.y),Math};
vm.createContext(context);
vm.runInContext(grips+'\nthis.findGripAt=findGripAt;',context);
assert.equal(context.findGripAt({x:24,y:0},false),null,'mouse hit target must stay precise');
const touchGrip=context.findGripAt({x:24,y:0},true);
assert.ok(touchGrip&&touchGrip.index===0&&touchGrip.key==='a','a 24px finger offset should still select the grip on iPhone');
const snap=extract('function snapCandidate(p,excludedIndex=-1){','function constrain(p){');
Object.assign(context,{osnapOn:true,osEnd:true,osMid:false,osCenter:false,osQuadrant:false,osIntersection:false,osGeom:false,osInsertion:false,osTangent:false,osExtension:false,osApparent:false,osPerpendicular:false,osNearest:true,hiddenLayers:new Set(),zoom:1,snapRadius:14,snapOn:false,gridStep:1,activeSnap:null,start:null,entitySegments:()=>[],pointLineDistance:()=>100,lineIntersection:()=>null});
vm.runInContext(snap+'\nthis.snapPoint=snapPoint;',context);
const ordinary=context.snapPoint({x:5,y:1});
assert.equal(ordinary.x,5);assert.equal(ordinary.y,0,'ordinary OSNAP nearest should still snap to a selected line');
const moving=context.snapPoint({x:5,y:1},0);
assert.equal(moving.x,5);assert.equal(moving.y,1,'dragging grip must ignore snapping to its own line in nearest mode');
assert.match(source,/setPointerCapture===\x27function\x27\)try\{canvas\.setPointerCapture/,'Safari pointer capture must have a guarded fallback');
assert.match(source,/gripDrag=\{\.\.\.grip,pointerId:e\.pointerId/,'grip tracking must lock to one finger');
assert.match(source,/if\(e\.pointerId!==gripDrag\.pointerId\)return/,'other fingers must not finish the active grip');
assert.match(source,/e\.pointerType===\x27touch\x27\)e\.preventDefault\(\)/,'Safari touch gestures must prevent page scrolling');
const html=fs.readFileSync('editor/index.html','utf8');
assert.match(html,/#stage,#cad\{-webkit-user-select:none;user-select:none;-webkit-touch-callout:none;touch-action:none/,'CAD canvas must suppress WebKit callouts during dragging');
assert.match(html,/rel="apple-touch-icon" sizes="180x180"/,'iPhone home screen icon must be linked from the editor');
console.log('iOS touch CAD regression passed: finger target, OSNAP exclusion, pointer capture, WebKit CSS and PWA icon');
